function pickLang() {
  let v = "auto";
  try { v = localStorage.getItem("cyn-lang") || "auto"; } catch {}
  if (v === "auto") v = (navigator.language || "en").slice(0, 2).toLowerCase();
  return LANGS[v] ? v : "en";
}
let LANG = pickLang();
document.documentElement.lang = LANG;

// Translate one UI string (exact match; leading/trailing spaces kept).
function t(s) {
  const d = I18N[LANG];
  if (!d || typeof s !== "string") return s;
  if (d[s]) return d[s];
  const m = s.match(/^(\s*)(.*?)(\s*)$/s);
  return m && d[m[2]] ? m[1] + d[m[2]] + m[3] : s;
}
const T_TAGS = new Set(["BUTTON", "H1", "H2", "H3", "H4", "TH", "LABEL", "OPTION", "SUMMARY", "LEGEND", "A"]);

// Static parts of index.html (sign-in form, menus)
function translatePage(root = document) {
  root.querySelectorAll("[data-t]").forEach((el) => { el.textContent = t(el.dataset.t || el.textContent.trim()); });
  root.querySelectorAll("[placeholder]").forEach((el) => el.setAttribute("placeholder", t(el.getAttribute("placeholder"))));
  root.querySelectorAll("[title]").forEach((el) => el.setAttribute("title", t(el.getAttribute("title"))));
}
